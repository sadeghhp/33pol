}

# --- Arg parsing ------------------------------------------------------------
COMMAND="${1:-help}"; shift || true
POSITIONAL=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --version)      VERSION="${2:?}"; shift 2 ;;
    --to)           ROLLBACK_TO="${2:?}"; shift 2 ;;
    --profiles)     PROFILES="${2:?}"; shift 2 ;;
    --restore-db)   RESTORE_DB_FILE="${2:?}"; shift 2 ;;
    --timeout)      HEALTH_TIMEOUT="${2:?}"; shift 2 ;;
    --keep)         KEEP="${2:?}"; shift 2 ;;
    --no-backup)    DO_BACKUP=false; shift ;;
    --hot)          HOT_BACKUP=true; shift ;;
    --no-health-gate) HEALTH_GATE=false; shift ;;
    -y|--yes)       ASSUME_YES=true; shift ;;
    --dry-run)      DRY_RUN=true; shift ;;
    -h|--help)      COMMAND="help"; shift ;;
    --) shift; while [[ $# -gt 0 ]]; do POSITIONAL+=("$1"); shift; done ;;
    -*) die "Unknown flag: $1  (see '$0 help')" ;;
    *)  POSITIONAL+=("$1"); shift ;;
  esac
done

case "${COMMAND}" in
  deploy)        cmd_deploy ;;
  rollback)      cmd_rollback ;;
  status)        cmd_status ;;
  versions)      cmd_versions ;;
  history)       cmd_history ;;
  backup)        cmd_backup ;;
  restore)       cmd_restore "${POSITIONAL[0]:-}" ;;
  list-backups)  cmd_list_backups ;;
  logs)          cmd_logs "${POSITIONAL[0]:-}" ;;
  prune)         cmd_prune ;;
  help|"")       usage ;;
  *)             err "Unknown command: ${COMMAND}"; usage; exit 1 ;;
esac
